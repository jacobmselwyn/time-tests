import pytest

from times import time_range, compute_overlap_time

@pytest.mark.parametrize(
    "first_args, second_args, expected",
    [
        (
            ("2010-01-12 10:00:00", "2010-01-12 12:00:00"),
            ("2010-01-12 12:30:00", "2010-01-12 13:00:00", 2, 60),
            [],
        ),
        (
            ("2010-01-12 10:00:00", "2010-01-12 12:00:00"),
            ("2010-01-12 12:00:00", "2010-01-12 13:00:00", 2, 60),
            [],
        ),
        (
            ("2010-01-12 10:00:00", "2010-01-12 12:00:00"),
            ("2010-01-12 10:30:00", "2010-01-12 10:45:00", 2, 60),
            [
                ("2010-01-12 10:30:00", "2010-01-12 10:37:00"),
                ("2010-01-12 10:38:00", "2010-01-12 10:45:00"),
            ],
        ),
        (
            ("2010-01-12 10:00:00", "2010-01-12 10:10:00", 2, 60),
            ("2010-01-12 10:02:00", "2010-01-12 10:12:00", 2, 60),
            [
                ("2010-01-12 10:02:00", "2010-01-12 10:04:30"),
                ("2010-01-12 10:05:30", "2010-01-12 10:06:30"),
                ("2010-01-12 10:07:30", "2010-01-12 10:10:00"),
            ],
        ),
    ],
)
def test_overlap(first_args, second_args, expected):
    first = time_range(*first_args)
    second = time_range(*second_args)
    assert compute_overlap_time(first, second) == expected


def test_date_going_backwards():
    with pytest.raises(ValueError):
        time_range(
            "2010-01-12 12:00:00",
            "2010-01-12 10:00:00"
        )
